-- Waiter temporary table reservations.
--
-- Schema notes:
--   * `waiter_table_reservations` holds bounded TTL reservations (10 minute
--     default). `order_id` is NULL while the reservation is a draft/seat
--     hold and is SET when the waiter confirms an order against it.
--   * The partial unique index below is the single concurrency guard:
--     `WHERE order_id IS NULL` means two concurrent claims of the same
--     unattached table can never both succeed. One raises a unique-violation
--     the other wins.
--   * `expires_at` is the safety valve: abandoned drafts are reclaimed by a
--     bounded TTL and released on client abandonment.
--   * No data is ever physically deleted. Cancelled/rescinded stays auditable.

CREATE TABLE waiter_table_reservations (
  id         BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  branch_id  BIGINT NOT NULL REFERENCES cafe_branches(id) ON DELETE CASCADE,
  table_id   BIGINT NOT NULL REFERENCES cafe_tables(id) ON DELETE RESTRICT,
  waiter_id  UUID   NOT NULL,
  order_id   BIGINT REFERENCES orders(id) ON DELETE SET NULL,
  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT waiter_table_reservations_pkey PRIMARY KEY (id)
);

CREATE INDEX idx_waiter_table_reservations_branch_table
  ON waiter_table_reservations (branch_id, table_id);

CREATE INDEX idx_waiter_table_reservations_waiter_expires
  ON waiter_table_reservations (waiter_id, expires_at);

-- No concurrent unconfirmed claims of the same table.
CREATE UNIQUE INDEX waiter_table_reservations_table_unconfirmed_uniq
  ON waiter_table_reservations (table_id)
  WHERE order_id IS NULL;
